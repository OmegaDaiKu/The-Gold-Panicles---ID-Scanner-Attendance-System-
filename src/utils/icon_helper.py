class IconHelper:
    """Loads Lucide SVG icons and tints them at runtime with per-(name, color, size) caching."""

    _icon_cache: dict = {}
    _pixmap_cache: dict = {}
    _missing_warned: set = set()

    @classmethod
    def get_base_dir(cls) -> Path:
        if hasattr(sys, "_MEIPASS"):
            return Path(sys._MEIPASS)
        return Path(__file__).resolve().parent.parent.parent

    @classmethod
    def _icon_dir(cls) -> Path:
        """Dynamically resolves icon directory relative to base application root."""
        return cls.get_base_dir() / "assets" / "icons" / "lucide"

    @classmethod
    def _resolve_svg_path(cls, name: str) -> Path:
        filename = name if name.endswith(".svg") else f"{name}.svg"
        return cls._icon_dir() / filename

    @classmethod
    def get_pixmap(cls, name: str, color: Optional[str] = None, size: int = 20) -> QPixmap:
        target_color = color if color is not None else Colors.TEXT_PRIMARY
        cache_key = (name, target_color, size)
        if cache_key in cls._pixmap_cache:
            return cls._pixmap_cache[cache_key]

        clean_name = name[:-4] if name.endswith(".svg") else name
        svg_path = cls._resolve_svg_path(clean_name)

        if svg_path.exists():
            renderer = QSvgRenderer(str(svg_path))
        elif clean_name in _INLINE_SVG_ICONS:
            svg_data = QByteArray(_INLINE_SVG_ICONS[clean_name].encode("utf-8"))
            renderer = QSvgRenderer(svg_data)
        else:
            if clean_name not in cls._missing_warned:
                logger.warning("IconHelper: Lucide icon '%s' not found -- rendering transparent fallback.", clean_name)
                cls._missing_warned.add(clean_name)
            blank = QPixmap(size, size)
            blank.fill(Qt.GlobalColor.transparent)
            cls._pixmap_cache[cache_key] = blank
            return blank

        pixmap = cls._render_renderer_tinted(renderer, target_color, size)
        cls._pixmap_cache[cache_key] = pixmap
        return pixmap

    @classmethod
    def get_icon(cls, name: str, color: Optional[str] = None, size: int = 20) -> QIcon:
        target_color = color if color is not None else Colors.TEXT_PRIMARY
        cache_key = (name, target_color, size)
        if cache_key in cls._icon_cache:
            return cls._icon_cache[cache_key]

        pixmap = cls.get_pixmap(name, color=target_color, size=size)
        icon = QIcon(pixmap)
        cls._icon_cache[cache_key] = icon
        return icon

    @staticmethod
    def _render_renderer_tinted(renderer: QSvgRenderer, color: str, size: int) -> QPixmap:
        """Renders vector SVG onto an ARGB32 QImage buffer, applies tint composition, and converts to a HiDPI QPixmap."""
        scaled_size = size * _RENDER_SCALE
        image = QImage(scaled_size, scaled_size, QImage.Format.Format_ARGB32_Premultiplied)
        image.fill(Qt.GlobalColor.transparent)

        painter = QPainter(image)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        renderer.render(painter, QRectF(0.0, 0.0, float(scaled_size), float(scaled_size)))
        painter.setCompositionMode(QPainter.CompositionMode.CompositionMode_SourceIn)
        painter.fillRect(image.rect(), Colors.parse_qcolor(color))
        painter.end()

        pixmap = QPixmap.fromImage(image)
        pixmap.setDevicePixelRatio(float(_RENDER_SCALE))
        return pixmap